import PredictionCard from "./PredictionCard";

function PredictionList({ predictions }) {
  if (!predictions || predictions.length === 0) {
    return (
      <div className="rounded-3xl border border-zinc-800 bg-[#161616] p-10 text-center shadow-xl">
        <div className="mx-auto flex h-16 w-16 items-center justify-center rounded-2xl bg-zinc-800">
          <span className="text-2xl">✨</span>
        </div>

        <h3 className="mt-5 text-xl font-semibold text-white">
          No Predictions Yet
        </h3>

        <p className="mt-2 text-zinc-400">
          Enter a phrase above to generate next-word predictions.
        </p>
      </div>
    );
  }

  return (
    <section className="space-y-6">
      {/* Section Header */}
      <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <h2 className="text-2xl font-bold text-white">
            Prediction Words
          </h2>

          <p className="mt-1 text-sm text-zinc-400">
            Ranked next-word predictions generated by the model.
          </p>
        </div>

        <div className="flex items-center gap-2 self-start rounded-full border border-yellow-500/30 bg-yellow-500/10 px-4 py-2">
          <span className="text-sm font-medium text-yellow-400">
            {predictions.length} Predictions
          </span>
        </div>
      </div>

      {/* Cards */}
      <div className="grid gap-6 md:grid-cols-2 grid-cols-3">
        {predictions.map((prediction) => (
          <PredictionCard
            key={`${prediction.word}-${prediction.rank}`}
            prediction={prediction}
          />
        ))}
      </div>
    </section>
  );
}

export default PredictionList;